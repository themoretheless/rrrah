import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
import assert from 'node:assert/strict';
const root=process.argv[2];
const helper=readFileSync(root+'/lib/scan-results.ts','utf8');
const source=readFileSync(root+'/lib/app-reducer.ts','utf8').replace(/^import type \{[\s\S]*?\} from "\.\/types"\r?$/m,'').replace(/^import \{ areScanResultsValid \} from "\.\/scan-results"\r?$/m,'');
const {appReducer:r}=await import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(helper+'\n'+source)).toString('base64'));
const report=(name,actual,expected)=>{assert.deepEqual(actual,expected);console.log(JSON.stringify({name,actual,passed:true}));};
const mediaItems={a:{mediaKey:'a'},b:{mediaKey:'b'},c:{mediaKey:'c'}};
const groups=[{id:'g',mediaKeys:['a','b','c'],originalMediaKey:'a',similarity:.99}];
const results={status:'results',mediaItems,groups,totalItems:3};
report('unknown-account-results-relabelled-as-new-account',r(results,{type:'HEALTH_CHECK_RESULT',payload:{success:true,hasGptk:true,accountEmail:'new'}}).accountEmail,'new');
let scan=r({status:'connected'},{type:'SCAN_STARTED',requestId:'old',hasGptk:true,accountEmail:'a'});
const cancelled=r(scan,{type:'SCAN_CANCELLED'});
report('scan-complete-after-cancellation-accepted',r(cancelled,{type:'SCAN_COMPLETE',mediaItems,groups}).status,'results');
report('health-check-during-scan-replaces-scan-state',r(scan,{type:'HEALTH_CHECK_RESULT',payload:{success:true,hasGptk:true,accountEmail:'a'}}).status,'connected');
const trash=r(results,{type:'TRASH_STARTED',mediaItems,groups,totalItems:3,totalToTrash:1});
