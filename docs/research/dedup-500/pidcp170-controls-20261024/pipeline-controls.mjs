import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {runPipeline} from './runtime/lib/pipeline.ts';
import {createSessionState} from './runtime/lib/state.ts';
import {DEFAULT_CONFIG} from './runtime/lib/config.ts';
const logger={info(){}};
const call=(id)=>({role:'assistant',content:[{type:'toolCall',id,name:'read',arguments:{path:'/owned/a'}}],timestamp:0});
const result=(id,text,isError=false)=>({role:'toolResult',toolCallId:id,toolName:'read',content:[{type:'text',text}],isError,timestamp:0});
const observations=[];
const old=[call('good'),result('good','valid earlier result'),call('bad'),result('bad','owned error',true)];
const config=structuredClone(DEFAULT_CONFIG);
const recent=runPipeline(old,config,createSessionState(),logger);
assert.equal(recent.dedupPruned,0);
observations.push({case:'default recency protects recent duplicate/error pair',dedupPruned:recent.dedupPruned});
const aged=[...old,...Array.from({length:4},(_,i)=>({role:'user',content:'later turn '+i,timestamp:i+1}))];
const snapshot=JSON.stringify(aged);
const agedRun=runPipeline(aged,config,createSessionState(),logger);
assert.equal(agedRun.dedupPruned,1);
assert(agedRun.messages[1].content[0].text.startsWith('[pruned by pi-dcp:'));
assert.equal(JSON.stringify(aged),snapshot);
observations.push({case:'default pipeline removes aged successful result when latest repeat is an error',dedupPruned:agedRun.dedupPruned,originalsUnchanged:true});
const purgeConfig=structuredClone(DEFAULT_CONFIG);
purgeConfig.turnProtection.enabled=false;
for(const name of ['deduplication','overlapDedup','supersession','sizeAgeDecay'])purgeConfig.strategies[name].enabled=false;
const state=createSessionState();state.turnIndex=10;state.erroredAt.set('failure',0);
const messages=[call('failure'),result('failure','owned error',true)];
const originalArgs=JSON.stringify(messages[0].content[0].arguments);
const first=runPipeline(messages,purgeConfig,state,logger);
assert.equal(first.errorInputsPurged,1);
assert.equal(first.messages[0].content[0].arguments.__purged,'[args purged by pi-dcp]');
const second=runPipeline(messages,purgeConfig,state,logger);
assert.equal(second.errorInputsPurged,0);
assert.equal(JSON.stringify(second.messages[0].content[0].arguments),originalArgs);
observations.push({case:'fresh-original second pass restores errored arguments because tracking suppresses rewrite',firstPurged:first.errorInputsPurged,secondPurged:second.errorInputsPurged,secondArgs:second.messages[0].content[0].arguments,originalsUnchanged:JSON.stringify(messages[0].content[0].arguments)===originalArgs});
const payload={scope:'Complete original runPipeline and imported strategy/messages/config/state/token modules; lifetime-stat persistence replaced by explicit in-memory bumpLifetime adapter and logger observer. Owned message fixtures, no config loading, user storage, host Pi or provider execution.',authored_controls_run:3,observations};
writeFileSync(new URL('pipeline-results.json',import.meta.url),JSON.stringify(payload,null,2)+'\n');
console.log(JSON.stringify(payload,null,2));
