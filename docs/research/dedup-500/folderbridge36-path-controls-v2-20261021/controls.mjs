import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
import assert from 'node:assert/strict';
const root=process.argv[2];
const url=s=>`data:text/javascript;base64,${Buffer.from(s).toString('base64')}`;
const mocks=url(stripTypeScriptTypes(readFileSync(`${root}/tests/__mocks__/obsidian.ts`,'utf8'),{mode:'transform'}));
let source=readFileSync(`${root}/src/PathMapper.ts`,'utf8').replace(/^import .*\n/gm,'');
source=source.replace(/^const path:.*\n/m,'');
const {PathMapper}=await import(url(`import path from 'node:path';import {normalizePath} from '${mocks}';\n${stripTypeScriptTypes(source)}`));
const mount=(id,virtualPath,realPath)=>({id,virtualPath,realPath,enabled:true});
const mapper=new PathMapper();
let outer=mount('a','Work','/base'),inner=mount('b','Work/Nested','/nested');
mapper.update([outer,inner]);assert.equal(mapper.getMountForPath('Work/Nested/a.md'),inner);
console.log(JSON.stringify({name:'longest-mount-selected',passed:true}));
mapper.setResolvedPath('a','/fallback');const changed={...outer,realPath:'/new'};mapper.update([changed]);assert.equal(mapper.getEffectiveRealPath(changed),'/new');
console.log(JSON.stringify({name:'same-id-root-change-invalidates-resolution',passed:true}));
assert.equal(mapper.toVirtualPath('/new/..notes.md',changed),'Work');
console.log(JSON.stringify({name:'legal-dotdot-prefixed-basename-collapses-to-root',passed:true,actual:'Work'}));
outer=mount('a','One','/same');inner=mount('b','Two','/same');mapper.update([outer,inner]);assert.equal(mapper.toRealPath('One/a.md',outer),mapper.toRealPath('Two/a.md',inner));assert.equal(mapper.getMounts().length,2);
console.log(JSON.stringify({name:'different-virtual-paths-can-alias-same-real-path',passed:true}));
