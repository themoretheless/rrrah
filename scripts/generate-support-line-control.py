#!/usr/bin/env python3
"""Exact rational triangle-union control, independent of Rust line provenance."""
from fractions import Fraction as F
from itertools import combinations
from pathlib import Path
import json
import struct

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'tests/fixtures/geometry/clip-support-five.json').read_text())
def number(bits):
    return F.from_float(struct.unpack('>d', struct.pack('>Q', bits))[0])
def cross(a, b, c):
    return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
def clip(poly, triangle):
    for a,b in zip(triangle, triangle[1:]+triangle[:1]):
        if not poly:
            break
        out=[]
        prev=poly[-1]; f=cross(a,b,prev)
        for point in poly:
            g=cross(a,b,point)
            if (f >= 0) != (g >= 0):
                t=f/(f-g)
                out.append(tuple(prev[k]+t*(point[k]-prev[k]) for k in range(2)))
            if g >= 0:
                out.append(point)
            prev=point; f=g
        poly=out
    return poly
def area(poly):
    if len(poly)<3:
        return F(0)
    return abs(sum(cross(poly[0], poly[i], poly[i+1]) for i in range(1,len(poly)-1)))/2
triangles=[]
for row in data['rows']:
    t=[tuple(number(b) for b in p) for p in row[3]]
    if cross(*t)<0:
        t[1],t[2]=t[2],t[1]
    triangles.append(t)
expected=[]
fractions=[]
for end in range(1,len(triangles)+1):
    union=F(0)
    for count in range(1,end+1):
        for indices in combinations(range(end),count):
            p=triangles[indices[0]]
            for i in indices[1:]:
                p=clip(p,triangles[i])
            union += area(p) * (1 if count%2 else -1)
    expected.append(struct.unpack('>Q',struct.pack('>d',float(union)))[0])
    fractions.append(str(union))
rows=''.join('('+str(r[0])+','+str(r[1])+','+str(r[2])+','+str(r[3])+','+str(r[4])+'),\n' for r in data['rows'])
(root/'tests/fixtures/geometry/clip-support-five.rs').write_text('// Generated by scripts/generate-support-line-control.py using exact Fraction union.\n(&[\n'+rows+'], '+str(expected)+')\n')
print(json.dumps({'prefix_union_bits':expected,'exact_prefix_union':fractions},indent=2))
