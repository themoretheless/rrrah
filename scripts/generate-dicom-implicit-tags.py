"""Generate native public-tag/sequence classifications from PS3.6 facts.
Generator dependency only: pydicom3.0.2. Production never imports pydicom.
Unknown public tags remain unsupported; private defined-length values are opaque.
"""
from pathlib import Path
import hashlib
import pydicom
from pydicom.datadict import DicomDictionary, RepeatersDictionary
assert pydicom.__version__=='3.0.2'
root=Path(__file__).resolve().parents[1]
source=Path(pydicom.__file__).parent/'_dicom_dict.py'
known=sorted(DicomDictionary)
sequences=sorted(tag for tag,v in DicomDictionary.items() if v[0]=='SQ')
def array(name,values):
    lines=['#[rustfmt::skip]',f'pub(super) const {name}: &[u32] = &[']
    for at in range(0,len(values),8):lines.append('    '+''.join(f'0x{tag:08x}, ' for tag in values[at:at+8]))
    return '\n'.join(lines+["];",''])
text='// Generated by scripts/generate-dicom-implicit-tags.py; do not edit.\n'
text+='// PS3.6 tag/VR facts via pydicom3.0.2, MIT; data/pydicom-dictionary-LICENSE.txt.\n'
text+=f'// Input dictionary SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
text+=array('KNOWN',known)+array('SEQUENCES',sequences)
text+='#[rustfmt::skip]\npub(super) const REPEATERS: &[(u32,u32,bool)] = &[\n'
for pattern,value in sorted(RepeatersDictionary.items()):
    mask=int(''.join('0' if c.lower()=='x' else 'f' for c in pattern),16)
    tag=int(pattern.replace('x','0').replace('X','0'),16)
    text+=f'    (0x{mask:08x},0x{tag:08x},{str(value[0]=="SQ").lower()}),\n'
text+='];\n'
out=root/'crates/rrrah-scientific/src/dicom_implicit_tags.rs';out.write_text(text)
license_path=Path(pydicom.__file__).parent.parent/'pydicom-3.0.2.dist-info/licenses/LICENSE'
license_out=root/'crates/rrrah-scientific/data/pydicom-dictionary-LICENSE.txt';license_out.parent.mkdir(exist_ok=True);license_out.write_bytes(license_path.read_bytes())
print('public',len(known),'sequences',len(sequences),'repeaters',len(RepeatersDictionary))
